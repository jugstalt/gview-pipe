using gView.Pipe.Abstraction.Credentials;
using gView.Pipe.Abstraction.Nodes;
using gView.Pipe.Core.Plugins;
using System.ComponentModel.DataAnnotations;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace gView.Pipe.Docs;

/// <summary>Turns the plugin catalog into Markdown pages: an index, one page per node category and the credential types.</summary>
static internal class NodeReferenceWriter
{
    const string Generated = "<!-- Generated by src/gView.Pipe.Docs from the node attributes. Don't edit. -->";

    // the order of the palette; unknown categories follow alphabetically
    static private readonly string[] CategoryOrder = ["Triggers", "Flow", "Transform", "Network", "Files", "Database", "Scripts", "Utility"];

    /// <returns>The number of pages written.</returns>
    static public int Write(PipePluginCatalog catalog, string output)
    {
        if (Directory.Exists(output))
        {
            Directory.Delete(output, recursive: true);
        }
        Directory.CreateDirectory(output);

        var categories = catalog.Nodes
            .Where(n => !n.Obsolete)
            .GroupBy(n => n.Category)
            .OrderBy(g => Array.IndexOf(CategoryOrder, g.Key) is var i and >= 0 ? i : int.MaxValue)
            .ThenBy(g => g.Key, StringComparer.OrdinalIgnoreCase)
            .ToList();

        var credentialNames = catalog.CredentialTypes.ToDictionary(t => t.Id, t => t.Name);

        foreach (var category in categories)
        {
            WriteFile(output, $"{Slug(category.Key)}.md", CategoryPage(category.Key, category.OrderBy(n => n.Name, StringComparer.OrdinalIgnoreCase), credentialNames));
        }
        WriteFile(output, "credential-types.md", CredentialTypesPage(catalog.CredentialTypes));
        WriteFile(output, "index.md", IndexPage(categories));

        return categories.Count + 2;
    }

    static private string IndexPage(List<IGrouping<string, PipeNodeDescriptor>> categories)
    {
        var text = new StringBuilder();
        text.AppendLine(Generated).AppendLine();
        text.AppendLine("# Node reference").AppendLine();
        text.AppendLine("All nodes of this version, with their parameters. The pages are generated from the node classes, so they always match the app.");
        text.AppendLine("Parameters marked as supporting expressions accept `{{ … }}` (JavaScript). The names in `code` are the keys in the workflow JSON.").AppendLine();

        foreach (var category in categories)
        {
            text.AppendLine($"## [{category.Key}]({Slug(category.Key)}.md)").AppendLine();
            text.AppendLine("| Node | Description |").AppendLine("|---|---|");
            foreach (var node in category.OrderBy(n => n.Name, StringComparer.OrdinalIgnoreCase))
            {
                text.AppendLine($"| [{node.Name}]({Slug(category.Key)}.md#{Slug(node.Name)}) | {Cell(FirstSentence(node.Description))} |");
            }
            text.AppendLine();
        }

        text.AppendLine("## Credential types").AppendLine();
        text.AppendLine("See [Credential types](credential-types.md).");
        return text.ToString();
    }

    static private string CategoryPage(string category, IEnumerable<PipeNodeDescriptor> nodes, Dictionary<Guid, string> credentialNames)
    {
        var text = new StringBuilder();
        text.AppendLine(Generated).AppendLine();
        text.AppendLine($"# {category}").AppendLine();

        foreach (var node in nodes)
        {
            text.AppendLine($"## {node.Name}").AppendLine();
            if (!string.IsNullOrWhiteSpace(node.Description))
            {
                text.AppendLine(Html(node.Description.Trim())).AppendLine();
            }

            text.AppendLine(Ports(node)).AppendLine();

            var parameters = Parameters(node, credentialNames);
            if (parameters.Count == 0)
            {
                text.AppendLine("This node has no parameters.").AppendLine();
                continue;
            }

            text.AppendLine("| Parameter | Type | Description |").AppendLine("|---|---|---|");
            foreach (var parameter in parameters)
            {
                text.AppendLine($"| **{Cell(parameter.Label)}**{(parameter.Required ? " (required)" : "")}<br>`{parameter.Key}` | {Cell(parameter.Type)} | {Cell(parameter.Description)} |");
            }
            text.AppendLine();
        }

        return text.ToString();
    }

    static private string CredentialTypesPage(IReadOnlyList<PipeCredentialTypeDescriptor> types)
    {
        var text = new StringBuilder();
        text.AppendLine(Generated).AppendLine();
        text.AppendLine("# Credential types").AppendLine();
        text.AppendLine("Credentials are stored encrypted. Nodes reference them by id; secret fields are never shown again after saving.").AppendLine();

        foreach (var type in types.OrderBy(t => t.Name, StringComparer.OrdinalIgnoreCase))
        {
            text.AppendLine($"## {type.Name}").AppendLine();
            if (!string.IsNullOrWhiteSpace(type.Description))
            {
                text.AppendLine(Html(type.Description.Trim())).AppendLine();
            }

            text.AppendLine("| Field | Type | |").AppendLine("|---|---|---|");
            foreach (var property in type.DataType.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.CanWrite))
            {
                var secret = property.GetCustomAttribute<SecretAttribute>() is not null ? "secret" : "";
                text.AppendLine($"| `{Key(property.Name)}` | {Cell(TypeName(property.PropertyType))} | {secret} |");
            }
            text.AppendLine();
        }

        return text.ToString();
    }

    static private string Ports(PipeNodeDescriptor node)
    {
        if (node.HasDynamicPorts)
        {
            return "**Ports:** depend on the parameters.";
        }

        var inputs = node.Inputs.Count == 0 ? "none (starts the workflow)" : string.Join(", ", node.Inputs.Select(p => $"`{p.Name}`"));
        var outputs = node.Outputs.Count == 0 ? "none" : string.Join(", ", node.Outputs.Select(p => $"`{p.Name}`"));
        return $"**Inputs:** {inputs} · **Outputs:** {outputs}";
    }

    static private List<ParameterInfoRow> Parameters(PipeNodeDescriptor node, Dictionary<Guid, string> credentialNames)
    {
        if (node.ParametersType is null)
        {
            return [];
        }

        object? defaults = null;
        try
        {
            defaults = Activator.CreateInstance(node.ParametersType);
        }
        catch (MissingMethodException)
        {
            // no default constructor: no defaults shown
        }

        var rows = new List<(int Order, ParameterInfoRow Row)>();
        foreach (var property in node.ParametersType.GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (property.GetCustomAttribute<PipeParameterAttribute>() is not { } attribute)
            {
                continue;
            }

            var type = UnderlyingType(property.PropertyType);
            var details = new List<string>();
            if (!string.IsNullOrWhiteSpace(attribute.Description))
            {
                details.Add(attribute.Description.Trim().TrimEnd('.') + ".");
            }

            if (attribute.Code)
            {
                details.Add("Source code; `{{ }}` is not evaluated.");
            }
            else if (attribute.Expressions && IsText(type))
            {
                details.Add("Supports expressions.");
            }

            if (DefaultText(property, defaults, type) is { } defaultText)
            {
                details.Add($"Default: `{defaultText}`.");
            }

            var typeName = TypeName(property.PropertyType);
            if (property.GetCustomAttribute<PipeCredentialAttribute>() is { } credential)
            {
                var names = credential.CredentialTypeIds.Select(id => credentialNames.GetValueOrDefault(id, id.ToString())).ToList();
                typeName = names.Count == 0 ? "credential" : $"credential ({string.Join(", ", names)})";
            }
            else if (property.GetCustomAttribute<PipeWorkflowReferenceAttribute>() is not null)
            {
                typeName = "workflow";
            }
            else if (attribute.Code)
            {
                typeName = "code";
            }

            rows.Add((attribute.Order, new ParameterInfoRow(
                attribute.Label ?? property.Name,
                Key(property.Name),
                typeName,
                property.GetCustomAttribute<RequiredAttribute>() is not null,
                string.Join(" ", details))));
        }

        return rows.OrderBy(r => r.Order).Select(r => r.Row).ToList();
    }

    /// <summary>Simple defaults only: random or generated values (like a new path) would change with every run.</summary>
    static private string? DefaultText(PropertyInfo property, object? defaults, Type type)
    {
        if (defaults is null || !(type.IsEnum || type == typeof(bool) || type.IsPrimitive || type == typeof(decimal)))
        {
            return null;
        }

        var value = property.GetValue(defaults);
        return value switch
        {
            null => null,
            Enum e => EnumName(e.ToString()),
            bool b => b ? "true" : "false",
            _ => Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture)
        };
    }

    static private string TypeName(Type type)
    {
        type = UnderlyingType(type);

        if (type.IsEnum)
        {
            return "one of: " + string.Join(", ", Enum.GetNames(type).Select(n => $"`{EnumName(n)}`"));
        }
        if (type == typeof(string))
        {
            return "text";
        }
        if (type == typeof(bool))
        {
            return "true/false";
        }
        if (type == typeof(int) || type == typeof(long) || type == typeof(short) || type == typeof(byte))
        {
            return "integer";
        }
        if (type == typeof(double) || type == typeof(float) || type == typeof(decimal))
        {
            return "number";
        }
        if (typeof(JsonNode).IsAssignableFrom(type) || type == typeof(JsonElement))
        {
            return "JSON";
        }
        if (type.IsGenericType && type.GetGenericTypeDefinition() == typeof(Dictionary<,>))
        {
            return "key/value pairs";
        }
        if (type.IsArray)
        {
            return ListName(type.GetElementType()!);
        }
        if (type.IsGenericType && type.GetGenericArguments().Length == 1 && typeof(System.Collections.IEnumerable).IsAssignableFrom(type))
        {
            return ListName(type.GetGenericArguments()[0]);
        }

        // classes of the plugins are internal details: shown as "object"
        return "object";
    }

    static private string ListName(Type element)
    {
        var name = TypeName(element);
        return name == "object" ? "list" : "list of " + name;
    }

    static private Type UnderlyingType(Type type) => Nullable.GetUnderlyingType(type) ?? type;

    static private bool IsText(Type type) => type == typeof(string) || typeof(JsonNode).IsAssignableFrom(type);

    // the same names the JSON has: camelCase
    static private string Key(string name) => JsonNamingPolicy.CamelCase.ConvertName(name);

    static private string EnumName(string name) => JsonNamingPolicy.CamelCase.ConvertName(name);

    static private string FirstSentence(string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return "";
        }

        var end = text.IndexOf(". ", StringComparison.Ordinal);
        return (end < 0 ? text : text[..(end + 1)]).Trim();
    }

    static private string Cell(string? text)
        => Html(text).Replace("|", "\\|").Replace("\r", "").Replace("\n", "<br>");

    // descriptions are plain text: "<path>" must not become a tag
    static private string Html(string? text) => (text ?? "").Replace("<", "&lt;").Replace(">", "&gt;");

    // the slug MkDocs makes for a heading: lower case, everything else becomes '-'
    static private string Slug(string text)
    {
        var slug = new StringBuilder();
        foreach (var character in text.ToLowerInvariant())
        {
            if (char.IsLetterOrDigit(character))
            {
                slug.Append(character);
            }
            else if (slug.Length > 0 && slug[^1] != '-')
            {
                slug.Append('-');
            }
        }
        return slug.ToString().TrimEnd('-');
    }

    static private void WriteFile(string folder, string name, string content)
        => File.WriteAllText(Path.Combine(folder, name), content.Replace("\r\n", "\n"), new UTF8Encoding(false));

    private sealed record ParameterInfoRow(string Label, string Key, string Type, bool Required, string Description);
}
